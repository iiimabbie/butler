import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { messageAttachmentContent, isOrdinaryZip } from '../dist/input-attachments.js';
const zip=Buffer.from([0x50,0x4b,0x03,0x04,0,0,0,0]);
const att=(filename,mimeType)=>({filename,mimeType});
assert.equal(isOrdinaryZip(att('x.zip','application/octet-stream'),zip),true);
assert.equal(isOrdinaryZip(att('x.docx','application/zip'),zip),true,'ZIP MIME must not be bypassed by OOXML extension');
assert.equal(isOrdinaryZip(att('x.docx','application/vnd.openxmlformats-officedocument.wordprocessingml.document'),zip),false);
assert.equal(isOrdinaryZip(att('x.bin','application/octet-stream'),Buffer.from([0x50,0x4b,0x05,0x04])),false,'signature must match exactly');
const root=mkdtempSync(join(tmpdir(),'butler-zip-')); const incoming=join(root,'incoming'); mkdirSync(incoming);
try {
 const id='74cab773-bdfd-4ccb-a542-8cf63351ca9b'; const path=join(incoming,id+'.bin');

 // A valid tiny ZIP generated by Python fixture in the Python test; make opaque fake ZIP for no unsafe file interaction.
 writeFileSync(path,zip);
 const record={attachmentId:'x',filename:'sample.zip',mimeType:'application/zip',size:zip.length,status:'ready',localPath:path};
 const message={role:'user',createdAt:'now',content:'look',discordSegments:[],source:{}};
 const result=messageAttachmentContent({...message,attachments:[record]},root);
 assert.equal(result.some(x=>x.type==='input_file'),false);
 assert.match(result.map(x=>x.text||'').join(' '),/ZIP 附件/);
 const ordinary={...record,filename:'file.docx',mimeType:'application/vnd.openxmlformats-officedocument.wordprocessingml.document'};
 const regular=messageAttachmentContent({...message,attachments:[ordinary]},root);
 assert.equal(regular.some(x=>x.type==='input_file'),true);
 execFileSync('/usr/bin/python3', ['-c', "import zipfile,sys\nwith zipfile.ZipFile(sys.argv[1],'w') as z: z.writestr('notes.txt','hello safe integration')", path]);
 const previousCwd=process.cwd();
 try {
  process.chdir(tmpdir());
  const valid=messageAttachmentContent({...message,attachments:[{...record,size: (await import('node:fs')).statSync(path).size}]},root);
  assert.equal(valid.some(x=>x.type==='input_file'),false);
  assert.match(valid.map(x=>x.text||'').join(' '),/hello safe integration/);
 } finally { process.chdir(previousCwd); }
 // The same shared renderer accepts legacy ready records as well as freshly prepared records.
 const historical={...record,attachmentId:'old',filename:'old.zip'};
 assert.equal(messageAttachmentContent({...message,attachments:[historical]},root).some(x=>x.type==='input_file'),false);
} finally { rmSync(root,{recursive:true,force:true}); }
console.log('ZIP routing and shared attachment regression checks passed');
